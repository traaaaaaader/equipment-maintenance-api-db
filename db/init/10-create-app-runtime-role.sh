#!/bin/sh

set -e

: "${APP_PGUSER:?APP_PGUSER is required}"
: "${APP_PGPASSWORD:?APP_PGPASSWORD is required}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
	CREATE ROLE "$APP_PGUSER" LOGIN PASSWORD '$APP_PGPASSWORD';
	GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$APP_PGUSER";
	GRANT USAGE ON SCHEMA public TO "$APP_PGUSER";
	GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "$APP_PGUSER";
	ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER" IN SCHEMA public
	  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$APP_PGUSER";
SQL

if [ -n "$APP_DB_NAME_TEST" ]; then
	createdb --username "$POSTGRES_USER" --owner "$POSTGRES_USER" "$APP_DB_NAME_TEST"
fi
